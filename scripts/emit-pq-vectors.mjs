// Emits test/pq-vectors.json — the cross-implementation contract between the
// PWA's hybrid post-quantum crypto and the Flutter app's pure-Dart port.

import fs from 'node:fs';
import path from 'node:path';
import { loadNym, root, hex } from './pq-harness.mjs';

const { NostrTools: T, NymCrypto: NC } = loadNym();
const kem = globalThis.NymMlKem.ml_kem768;

// Deterministic filler bytes; no CSPRNG anywhere in this file.
const fill = (n, b) => new Uint8Array(n).fill(b);
const seq = (n, start = 0) => Uint8Array.from({ length: n }, (_, i) => (start + i * 7 + (i >> 3)) & 0xff);

// The previous emission, if present. Only used to keep BIP-340 signatures
// stable across runs; every other value is recomputed from scratch.
let prior = null;
try {
    prior = JSON.parse(fs.readFileSync(path.join(root, 'test', 'pq-vectors.json'), 'utf8'));
} catch (_) { /* first run */ }

const out = {
    _comment: 'Generated by scripts/emit-pq-vectors.mjs. Do not hand-edit. Identical copy lives in the Flutter repo at test/pq-vectors.json.',
    scheme: {
        kem: 'ML-KEM-768 (FIPS 203)',
        classical: 'secp256k1 ECDH (NIP-44 style: 02||x lift, 32-byte big-endian shared x)',
        combiner: 'HKDF-Extract-SHA256(salt, ecdhX || kemSs || kemCt || recipKemPk || senderSecpPk || recipSecpPk)',
        combinerSalt: 'nymchat-pq-v1',
        seedSalt: 'nym-pq-v1',
        seedInfo: 'mlkem768/epoch/<epoch>',
        contentPrefix: 'pq1.',
        contentFormat: 'pq1.<base64url-nopad(kemCiphertext)>.<NIP-44 v2 payload>',
        sizes: { kemPublicKey: 1184, kemSecretKey: 2400, kemCiphertext: 1088, sharedSecret: 32 },
    },
    seedDerivation: [],
    keygen: [],
    decapsulate: [],
    conversationKey: [],
    endToEnd: [],
    giftWrap: null,
    announcement: null,
};

// --- 1. nsec -> ML-KEM seed (must be identical on every device) -------------
for (const [pkFill, epoch] of [[0x11, 0], [0x11, 1], [0xa7, 5]]) {
    const privkey = fill(32, pkFill);
    out.seedDerivation.push({
        privkey: hex(privkey),
        epoch,
        seed: hex(NC.pqDeriveSeed(privkey, epoch)),
    });
}

// --- 2. seed -> ML-KEM keypair ---------------------------------------------
for (const s of [fill(64, 0x2b), seq(64, 3)]) {
    const kp = kem.keygen(s);
    out.keygen.push({ seed: hex(s), publicKey: hex(kp.publicKey), secretKey: hex(kp.secretKey) });
}

// --- 3. decapsulation (exercises the NTT / FO transform end to end) ---------
// Includes an implicit-rejection case: ML-KEM never "fails", it returns a
// pseudorandom secret for a bad ciphertext. A port that throws there is wrong.
{
    const kp = kem.keygen(fill(64, 0x40));
    for (const m of [fill(32, 0x55), seq(32, 11)]) {
        const e = kem.encapsulate(kp.publicKey, m);
        out.decapsulate.push({
            keySeed: hex(fill(64, 0x40)),
            encapsulationRandomness: hex(m),
            cipherText: hex(e.cipherText),
            sharedSecret: hex(e.sharedSecret),
            note: 'valid ciphertext',
        });
    }
    const good = kem.encapsulate(kp.publicKey, fill(32, 0x55));
    const bad = Uint8Array.from(good.cipherText);
    bad[0] ^= 0x01;
    out.decapsulate.push({
        keySeed: hex(fill(64, 0x40)),
        cipherText: hex(bad),
        sharedSecret: hex(kem.decapsulate(bad, kp.secretKey)),
        note: 'implicit rejection: corrupted ciphertext must return a pseudorandom secret, NOT throw',
    });
}

// --- 4. the hybrid combiner in isolation ------------------------------------
for (const [a, b] of [[0x01, 0x02], [0x30, 0x31], [0xfe, 0x0f]]) {
    const senderSk = fill(32, a), recipSk = fill(32, b);
    const senderPk = T.getPublicKey(senderSk), recipPk = T.getPublicKey(recipSk);
    const kp = kem.keygen(fill(64, a ^ 0x5a));
    const e = kem.encapsulate(kp.publicKey, fill(32, b ^ 0x33));
    const ecdhX = T._secp256k1.getSharedSecret(senderSk, '02' + recipPk).subarray(1, 33);
    out.conversationKey.push({
        senderSecpPubkey: senderPk,
        recipSecpPubkey: recipPk,
        ecdhSharedX: hex(ecdhX),
        kemSharedSecret: hex(e.sharedSecret),
        kemCipherText: hex(e.cipherText),
        recipKemPublicKey: hex(kp.publicKey),
        conversationKey: hex(NC.pqConversationKey(
            ecdhX, e.sharedSecret, e.cipherText, kp.publicKey, senderPk, recipPk)),
    });
}

// --- 5. full payloads -------------------------------------------------------
// Built from the same three steps pqEncrypt performs, with the KEM randomness
// and NIP-44 nonce pinned. pqDecrypt (the real production path) is asserted to
// read each one back, so the Dart port must both reproduce the exact payload
// string and decrypt it.
// NIP-44 itself rejects empty plaintext (min 1 byte), so 'a' is the real
// lower boundary; the long case crosses the padding scheme's power-of-two
// buckets, which is where a mis-ported pad() would first show up.
const plaintexts = [
    'hello quantum world',
    'a',
    'unicode: éèê 中文 \u{1F510}\u{1F9EC} مرحبا',
    'x'.repeat(1000),
];
plaintexts.forEach((plaintext, i) => {
    const senderSk = fill(32, 0x71 + i), recipSk = fill(32, 0x91 + i);
    const senderPk = T.getPublicKey(senderSk), recipPk = T.getPublicKey(recipSk);
    const kemSeed = fill(64, 0xc0 + i);
    const kp = kem.keygen(kemSeed);
    const kemRandomness = fill(32, 0xd0 + i);
    const nonce = fill(32, 0xe0 + i);

    const e = kem.encapsulate(kp.publicKey, kemRandomness);
    const ecdhX = T._secp256k1.getSharedSecret(senderSk, '02' + recipPk).subarray(1, 33);
    const ck = NC.pqConversationKey(ecdhX, e.sharedSecret, e.cipherText, kp.publicKey, senderPk, recipPk);
    const payload = 'pq1.' + NC._b64uEncode(e.cipherText) + '.' + T.nip44.encrypt(plaintext, ck, nonce);

    const back = NC.pqDecrypt(payload, senderPk, { sk: recipSk, kemSk: kp.secretKey, kemPk: kp.publicKey });
    if (back !== plaintext) throw new Error(`self-check failed for vector ${i}`);

    out.endToEnd.push({
        senderPrivkey: hex(senderSk), senderPubkey: senderPk,
        recipPrivkey: hex(recipSk), recipPubkey: recipPk,
        recipKemSeed: hex(kemSeed),
        encapsulationRandomness: hex(kemRandomness),
        nip44Nonce: hex(nonce),
        conversationKey: hex(ck),
        plaintext,
        payload,
    });
});

// --- 6. a complete PQ gift wrap --------------------------------------------
// The payload vectors above cover the crypto; this covers the LAYERING — that a
// kind-1059 wrap built by one implementation is readable by the other, seal
// signature and all. Built from pinned components (ephemeral key, timestamps,
// KEM randomness, nonces) rather than by calling pqNip59Wrap, so the file stays
// reproducible; the decrypt direction is what actually matters for interop.
{
    const senderSk = fill(32, 0x5a);
    const senderPk = T.getPublicKey(senderSk);
    const recipSk = fill(32, 0x6b);
    const recipPk = T.getPublicKey(recipSk);
    const kemSeed = fill(64, 0x7c);
    const kp = kem.keygen(kemSeed);

    const rumor = {
        kind: 14,
        created_at: 1735689600,
        tags: [['p', recipPk], ['x', 'NYMTESTVECTOR0001'], ['ms', '1735689600000']],
        content: 'quantum-resistant gift wrap vector',
        pubkey: senderPk,
    };
    rumor.id = T.getEventHash(rumor);

    const mkPayload = (plaintext, sk, kemRand, nonce) => {
        const e = kem.encapsulate(kp.publicKey, kemRand);
        const ecdhX = T._secp256k1.getSharedSecret(sk, '02' + recipPk).subarray(1, 33);
        const ck = NC.pqConversationKey(
            ecdhX, e.sharedSecret, e.cipherText, kp.publicKey, T.getPublicKey(sk), recipPk);
        return 'pq1.' + NC._b64uEncode(e.cipherText) + '.' + T.nip44.encrypt(plaintext, ck, nonce);
    };

    // BIP-340 signing draws fresh aux_rand each call, so signing here would make
    // the file differ between runs even though every signed byte is identical.
    // Reuse the previously emitted signature whenever the event id (which
    // commits to all signed content) is unchanged; only genuinely new content
    // gets a fresh signature. `prior` is the file being regenerated.
    const signStable = (unsigned, sk, which) => {
        const ev = { ...unsigned, pubkey: T.getPublicKey(sk) };
        ev.id = T.getEventHash(ev);
        const old = prior?.giftWrap?.[which];
        if (old && old.id === ev.id && T.verifyEvent(old)) return old;
        return T.finalizeEvent(unsigned, sk);
    };

    const seal = signStable({
        kind: 13,
        content: mkPayload(JSON.stringify(rumor), senderSk, fill(32, 0x8d), fill(32, 0x9e)),
        created_at: 1735689000,
        tags: [],
    }, senderSk, 'seal');

    const ephSk = fill(32, 0xaf);
    const wrap = signStable({
        kind: 1059,
        content: mkPayload(JSON.stringify(seal), ephSk, fill(32, 0xb0), fill(32, 0xc1)),
        created_at: 1735688400,
        tags: [['p', recipPk]],
    }, ephSk, 'wrap');

    const check = NC.unwrapGiftWrap(wrap, [
        { sk: recipSk, bitchat: false, kemSk: kp.secretKey, kemPk: kp.publicKey },
    ]);
    if (!check || !check.isPq || check.rumor.content !== rumor.content) {
        throw new Error('gift wrap self-check failed');
    }

    out.giftWrap = {
        senderPubkey: senderPk,
        recipPrivkey: hex(recipSk),
        recipPubkey: recipPk,
        recipKemSeed: hex(kemSeed),
        rumor,
        seal,
        wrap,
    };
}

// --- 7. a kind-30078 'nym-pq' announcement ---------------------------------
// The discovery contract: the Flutter port must parse an announcement this
// client publishes (and reject the malformed variants identically), or the two
// will disagree about which peers are post-quantum capable.
{
    const sk = fill(32, 0xd4);
    const kp = kem.keygen(fill(64, 0xe5));
    const exp = 2000000000;
    const content = JSON.stringify({
        v: 1,
        alg: 'mlkem768',
        epoch: 2,
        pk: NC._b64uEncode(kp.publicKey),
        exp,
        devices: [
            { id: 'a1b2c3d4', ver: 'v3.74.533', ts: 1735689600 },
            { id: '0f1e2d3c', ver: 'v3.74.533', ts: 1735603200 },
        ],
    });
    out.announcement = {
        authorPubkey: T.getPublicKey(sk),
        kemSeed: hex(fill(64, 0xe5)),
        kemPublicKey: hex(kp.publicKey),
        expiresAt: exp,
        epoch: 2,
        content,
        retractionContent: JSON.stringify({ v: 1, alg: 'mlkem768', retracted: true, exp: 1735689600 }),
        // Each of these must be REJECTED, leaving the peer on classical.
        invalid: {
            notJson: 'not json',
            wrongAlg: JSON.stringify({ v: 1, alg: 'kyber512', pk: NC._b64uEncode(kp.publicKey), exp }),
            shortKey: JSON.stringify({ v: 1, alg: 'mlkem768', pk: NC._b64uEncode(new Uint8Array(32)), exp }),
            missingExp: JSON.stringify({ v: 1, alg: 'mlkem768', pk: NC._b64uEncode(kp.publicKey) }),
            expired: JSON.stringify({ v: 1, alg: 'mlkem768', pk: NC._b64uEncode(kp.publicKey), exp: 1000000000 }),
        },
    };
}

const dest = path.join(root, 'test', 'pq-vectors.json');
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${path.relative(root, dest)} (${fs.statSync(dest).size} bytes)`);
console.log(`  ${out.seedDerivation.length} seed, ${out.keygen.length} keygen, ${out.decapsulate.length} decaps, ${out.conversationKey.length} combiner, ${out.endToEnd.length} end-to-end`);
